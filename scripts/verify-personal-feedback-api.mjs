import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import test from "node:test";
import { personalFeedbackDigest } from "../server/personal-feedback.mjs";
import { personalFeedbackConsole } from "./fixtures/personal-feedback-console.mjs";

test("actual personal feedback HTTP preserves source scope, native replies, drafts, revisions and restart without inference", { timeout: 30_000 }, async t => {
  const fixture = await personalFeedbackConsole(); t.after(fixture.stop);
  const { request, state, control } = fixture;
  const endpoint = "/api/personal/sessions/personal-a/feedback";
  const initial = await request(endpoint);
  assert.equal(initial.status, 200); assert.equal(initial.body.enabled, true); assert.deepEqual(initial.body.feedback, []);
  const feedbackFile = path.join(state, "personal-message-feedback.json");
  await assert.rejects(fs.access(feedbackFile), { code: "ENOENT" });
  const read = await request("/api/chat/sessions?repoId=_personal&sessionId=personal-a");
  assert.equal(read.status, 200);
  const answer = read.body.messages.find(item => item.messageType === "agentMessage" && item.details?.phase === "final_answer");
  assert.equal(answer.turnStatus, "completed");
  const input = { turnId: answer.turnId, messageId: answer.id, contentDigest: personalFeedbackDigest(answer.text), decision: "helpful", expectedRevision: 0 };
  assert.equal((await request(endpoint, "POST", input, { origin: "https://untrusted.example" })).status, 403);
  for (const id of ["work-history", "work-thread", "app-work-thread", "unknown-personal"]) {
    assert.equal((await request(`/api/personal/sessions/${id}/feedback`)).status, 404);
    assert.equal((await request(`/api/personal/sessions/${id}/feedback`, "POST", input)).status, 404);
  }
  assert.equal((await request(endpoint, "POST", { ...input, unexpected: true })).status, 400);
  const saved = await request(endpoint, "POST", input);
  assert.equal(saved.status, 200); assert.equal(saved.body.feedback.revision, 1);
  const before = await fs.readFile(feedbackFile, "utf8");
  assert.equal(before.includes(answer.text), false);
  assert.equal((await request("/api/personal/sessions/feedback-thread-a/feedback", "POST", input)).body.feedback.revision, 1, "stored and native aliases resolve the same evaluation");
  assert.equal(await fs.readFile(feedbackFile, "utf8"), before);
  assert.equal((await request(endpoint, "POST", { ...input, decision: "not_helpful" })).status, 409);
  const config = JSON.parse(await fs.readFile(control, "utf8"));
  config.a.status = "inProgress"; await fs.writeFile(control, JSON.stringify(config));
  assert.equal((await request(endpoint, "POST", { ...input, decision: "not_helpful", expectedRevision: 1 })).status, 409);
  config.a.status = "completed"; config.a.text = "合成回复已变化"; await fs.writeFile(control, JSON.stringify(config));
  assert.equal((await request(endpoint, "POST", { ...input, decision: "not_helpful", expectedRevision: 1 })).status, 409);
  assert.equal(await fs.readFile(feedbackFile, "utf8"), before);
  config.a.text = answer.text; await fs.writeFile(control, JSON.stringify(config));
  const changed = await request(endpoint, "POST", { ...input, decision: "not_helpful", expectedRevision: 1 });
  assert.equal(changed.body.feedback.revision, 2);
  await fixture.restart();
  const after = await request(endpoint);
  assert.equal(after.body.feedback[0].decision, "not_helpful"); assert.equal(after.body.feedback[0].revision, 2);
  const summary = (await request("/api/personal/feedback")).body.summary;
  assert.equal(summary.ratedCount, 1); assert.equal(summary.helpfulCount, 0); assert.equal(summary.helpfulRatio, 0);
  const withdrawn = await request(endpoint, "POST", { ...input, decision: null, expectedRevision: 2 });
  assert.equal(withdrawn.body.feedback.revision, 3);
  assert.equal((await request("/api/personal/feedback")).body.summary.helpfulRatio, null);
  const chat = JSON.parse(await fs.readFile(path.join(state, "chat-history.json"), "utf8"));
  const original = Object.values(chat.sessions).find(session => session.codexSessionId === "feedback-thread-a");
  assert.equal(original.model, "gpt-6-astra"); assert.equal(original.reasoning, "ultra"); assert.equal(original.draft.input, "合成未发送草稿 A");
  const bytes = await fs.readFile(feedbackFile, "utf8");
  await fs.writeFile(feedbackFile, "{corrupt");
  assert.equal((await request(endpoint)).status, 503);
  assert.equal((await request("/api/personal/feedback")).status, 503);
  assert.equal((await request(endpoint, "POST", { ...input, expectedRevision: 3 })).status, 503);
  assert.equal(await fs.readFile(feedbackFile, "utf8"), "{corrupt");
  await fs.writeFile(feedbackFile, bytes);
  const rpc = (await fs.readFile(fixture.rpcCapture, "utf8")).trim().split("\n").map(line => JSON.parse(line));
  assert.equal(rpc.some(item => ["turn/start", "thread/start", "mcpServer/tool/call", "feedback/upload", "command/exec"].includes(item.method)), false);
});
